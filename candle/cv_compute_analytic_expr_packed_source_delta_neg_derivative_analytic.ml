(* ========================================================================== *)
(* Analytic identities for the optimized negative delta-derivative family.  *)
(*                                                                            *)
(* DEVELOPMENT / NON-RELEASE.  The three specialized source instructions     *)
(* compute [--(partial delta / partial x_i)] for i = 3,4,5.  This file        *)
(* identifies their value, gradient, and packed Hessian with one              *)
(* coordinate-parametric source expression generated by the proved symbolic  *)
(* differentiator.                                                            *)
(* ========================================================================== *)

needs "candle/cv_compute_polynomial_expr_diff.ml";;
needs "candle/cv_compute_analytic_expr_packed_source_delta_analytic.ml";;

module Candle_cv_analytic_expr_packed_source_delta_neg_derivative_analytic = struct

open Candle_cv_polynomial_expr_jet;;
open Candle_cv_polynomial_expr_dim_derivatives;;
open Candle_cv_polynomial_expr_diff;;
open Candle_cv_analytic_expr_jet;;
open Candle_cv_analytic_expr_packed_source_delta_value;;
open Candle_cv_analytic_expr_packed_source_delta_hessian;;
open Candle_cv_analytic_expr_packed_source_delta_analytic;;

let candle_packed_delta_neg_derivative_expr_def = new_definition
 `candle_packed_delta_neg_derivative_expr coordinate =
    Candle_analytic_poly
      (Candle_poly_neg
        (candle_poly_diff coordinate candle_packed_delta_poly))`;;

let candle_packed_delta_neg_derivative_poly_valid = prove
 (`!coordinate.
     coordinate < 6
     ==> candle_poly_valid_dim 6
           (Candle_poly_neg
             (candle_poly_diff coordinate candle_packed_delta_poly))`,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[candle_poly_valid_dim_def] THEN
  MATCH_MP_TAC candle_poly_diff_valid THEN
  REWRITE_TAC[candle_packed_delta_poly_valid]);;

let candle_packed_delta_neg_derivative_analytic_value = prove
 (`!env coordinate.
     candle_analytic_value env
       (candle_packed_delta_neg_derivative_expr coordinate) =
     --(candle_analytic_d coordinate env candle_packed_delta_expr)`,
  REWRITE_TAC[candle_packed_delta_neg_derivative_expr_def;
              candle_packed_delta_expr_def;
              candle_analytic_value_def; candle_analytic_d_def;
              candle_poly_value_list_def;
              candle_poly_diff_value_list]);;

let candle_packed_delta_neg_derivative_analytic_d = prove
 (`!env coordinate derivative_coordinate.
     candle_analytic_d derivative_coordinate env
       (candle_packed_delta_neg_derivative_expr coordinate) =
     --(candle_analytic_dd coordinate derivative_coordinate env
          candle_packed_delta_expr)`,
  REWRITE_TAC[candle_packed_delta_neg_derivative_expr_def;
              candle_packed_delta_expr_def;
              candle_analytic_d_def; candle_analytic_dd_def;
              candle_poly_d_list_def;
              candle_poly_diff_d_list]);;

let candle_real_packed_delta_basis_six_def = new_definition
 `candle_real_packed_delta_basis_six coordinate =
    [if coordinate = 0 then &1 else &0;
     if coordinate = 1 then &1 else &0;
     if coordinate = 2 then &1 else &0;
     if coordinate = 3 then &1 else &0;
     if coordinate = 4 then &1 else &0;
     if coordinate = 5 then &1 else &0]`;;

let candle_real_packed_delta_neg_derivative_hessian_six_def =
  new_definition
 `candle_real_packed_delta_neg_derivative_hessian_six coordinate =
    MAP (\value. --value)
      (candle_real_packed_delta_hessian_six
        (EL 0 (candle_real_packed_delta_basis_six coordinate))
        (EL 1 (candle_real_packed_delta_basis_six coordinate))
        (EL 2 (candle_real_packed_delta_basis_six coordinate))
        (EL 3 (candle_real_packed_delta_basis_six coordinate))
        (EL 4 (candle_real_packed_delta_basis_six coordinate))
        (EL 5 (candle_real_packed_delta_basis_six coordinate)))`;;

let candle_packed_delta_neg_derivative_analytic_dd_upper = prove
 (`!v0 v1 v2 v3 v4 v5 coordinate rowindex colindex.
     (coordinate = 3 \/ coordinate = 4 \/ coordinate = 5) /\
     rowindex < 6 /\ rowindex <= colindex /\ colindex < 6
     ==> candle_analytic_dd rowindex colindex
           [v0;v1;v2;v3;v4;v5]
           (candle_packed_delta_neg_derivative_expr coordinate) =
         EL (candle_packed_delta_hessian_upper_index rowindex colindex)
           (candle_real_packed_delta_neg_derivative_hessian_six coordinate)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  FIRST_X_ASSUM(REPEAT_TCL DISJ_CASES_THEN SUBST_ALL_TAC) THEN
  MP_TAC
   (ARITH_RULE
     `rowindex < 6
      ==> rowindex = 0 \/ rowindex = 1 \/ rowindex = 2 \/
          rowindex = 3 \/ rowindex = 4 \/ rowindex = 5`) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(REPEAT_TCL DISJ_CASES_THEN SUBST_ALL_TAC) THEN
  MP_TAC
   (ARITH_RULE
     `colindex < 6
      ==> colindex = 0 \/ colindex = 1 \/ colindex = 2 \/
          colindex = 3 \/ colindex = 4 \/ colindex = 5`) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(REPEAT_TCL DISJ_CASES_THEN SUBST_ALL_TAC) THEN
  TRY ASM_ARITH_TAC THEN
  REWRITE_TAC[candle_packed_delta_hessian_upper_index_def;
              candle_real_packed_delta_neg_derivative_hessian_six_def;
              candle_real_packed_delta_basis_six_def;
              candle_real_packed_delta_hessian_six_def;
              candle_real_packed_delta_hessian_rows_six_def;
              candle_real_packed_delta_sums_def;
              candle_real_packed_delta_sum_def;
              candle_real_packed_delta_sum_aux_def;
              candle_packed_delta_neg_derivative_expr_def;
              candle_packed_delta_poly_def;
              candle_analytic_dd_def; candle_poly_diff_def;
              candle_poly_dd_list_def; candle_poly_d_list_def;
              candle_poly_value_list_def;
              LET_DEF; LET_END_DEF; ITLIST; MAP] THEN
  CONV_TAC (DEPTH_CONV EL_CONV) THEN
  REWRITE_TAC[num_CONV `20`; num_CONV `19`; num_CONV `18`;
              num_CONV `17`; num_CONV `16`; num_CONV `15`;
              num_CONV `14`; num_CONV `13`; num_CONV `12`;
              num_CONV `11`; num_CONV `10`; num_CONV `9`;
              num_CONV `8`; num_CONV `7`; num_CONV `6`;
              num_CONV `5`; num_CONV `4`; num_CONV `3`;
              num_CONV `2`; num_CONV `1`; candle_q_real_lookup_def] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC (DEPTH_CONV EL_CONV) THEN
  REWRITE_TAC[candle_poly_dd_list_def; candle_poly_d_list_def;
              candle_poly_value_list_def; candle_poly_zero_real;
              candle_poly_one_real] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC REAL_RING);;

if exists (fun theorem -> hyp theorem <> [])
    [candle_packed_delta_neg_derivative_poly_valid;
     candle_packed_delta_neg_derivative_analytic_value;
     candle_packed_delta_neg_derivative_analytic_d;
     candle_packed_delta_neg_derivative_analytic_dd_upper] then
  failwith "packed source negative delta derivative analytic: assumptions";;

print_endline
  "CANDLE_CV_PACKED_SOURCE_DELTA_NEG_DERIVATIVE_ANALYTIC_OK DEVELOPMENT_NON_RELEASE";;

end;;
